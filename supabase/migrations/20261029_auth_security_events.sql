CREATE TABLE IF NOT EXISTS public.auth_security_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT NOT NULL CHECK (event_type IN ('login_success', 'login_failed', 'logout')),
    user_id TEXT NULL,
    identifier_hash CHAR(64) NOT NULL,
    ip_hash CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_auth_security_events_created_at
    ON public.auth_security_events (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_auth_security_events_identifier_created
    ON public.auth_security_events (identifier_hash, created_at DESC);

ALTER TABLE public.auth_security_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.auth_security_events FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.auth_security_events_id_seq FROM anon, authenticated;
